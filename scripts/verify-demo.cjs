    checkpoint('Vacante → interés simulado → lista de interesados del negocio');
    await visit('/panel');
    await click('Avisos');
    await click('Publicar aviso');
    await page.locator('#notice-form').getByLabel('Título',{exact:true}).fill('Aviso QA para jóvenes');
    await page.locator('#notice-form').getByLabel('Mensaje',{exact:true}).fill('Un aviso creado para probar las notificaciones.');
